#!/usr/bin/env python3
"""OS Maker GUI and project generator.

This script creates a minimal x86 assembly project and a Windows 7-inspired
Python desktop mockup. It is intended as a starter environment for learning OS
bootstrapping and assembly generation.
"""

import os
import shutil
import subprocess
import sys
import tkinter as tk
from tkinter import messagebox


class OSMakerApp(tk.Tk):
    def __init__(self):
        super().__init__()
        self.title("OS Maker")
        self.geometry("700x520")
        self.minsize(650, 500)
        self.configure(bg="#eef3f8")

        self.name_var = tk.StringVar(value="MyWin7OS")
        self.author_var = tk.StringVar(value="Your Name")

        self._build_ui()

    def _build_ui(self):
        title = tk.Label(
            self,
            text="OS Maker",
            font=("Segoe UI", 24, "bold"),
            fg="#1f2d3d",
            bg="#eef3f8",
            pady=18,
        )
        title.pack()

        form = tk.Frame(self, bg="#eef3f8")
        form.pack(fill="x", padx=28, pady=(0, 10))

        fields = [
            ("OS Name", self.name_var),
            ("Author", self.author_var),
        ]

        for label_text, var in fields:
            row = tk.Frame(form, bg="#eef3f8")
            row.pack(fill="x", pady=8)
            tk.Label(row, text=label_text, width=12, anchor="w", font=("Segoe UI", 11), bg="#eef3f8").pack(side="left")
            entry = tk.Entry(row, textvariable=var, width=44, font=("Segoe UI", 11))
            entry.pack(side="left", padx=(10, 0), fill="x", expand=True)

        buttons = tk.Frame(form, bg="#eef3f8")
        buttons.pack(fill="x", pady=16)

        generate_btn = tk.Button(buttons, text="Generate OS", command=self.generate_project, width=18, bg="#2e82d7", fg="white", font=("Segoe UI", 10, "bold"))
        generate_btn.pack(side="left")

        quit_btn = tk.Button(buttons, text="Quit", command=self.destroy, width=12, bg="#dfe7f1", fg="#1f2d3d", font=("Segoe UI", 10))
        quit_btn.pack(side="left", padx=(10, 0))

        log_label = tk.Label(self, text="Output", font=("Segoe UI", 11, "bold"), bg="#eef3f8", anchor="w")
        log_label.pack(fill="x", padx=28)

        self.log_area = tk.Text(self, height=16, wrap="word", bg="#ffffff", fg="#1d2735", font=("Consolas", 10))
        self.log_area.pack(fill="both", expand=True, padx=28, pady=(8, 18))
        self.log_area.insert(tk.END, "Ready. Enter an OS name and click Generate OS.\n")
        self.log_area.config(state="disabled")

    def log(self, text):
        self.log_area.config(state="normal")
        self.log_area.insert(tk.END, text + "\n")
        self.log_area.see(tk.END)
        self.log_area.config(state="disabled")

    def render_boot_asm(self, os_name):
        return f"""; Generated by OS Maker\n; OS: {os_name}\n\n[BITS 16]\n[ORG 0x7C00]\n\nstart:\n    cli\n    mov ax, 0x07C0\n    mov ds, ax\n    mov es, ax\n    mov ss, ax\n    mov sp, 0xFFFF\n    sti\n\n    mov si, loading_msg\n    call print_string\n\n    jmp $\n\nprint_string:\n    lodsb\n    or al, al\n    jz .done\n    mov ah, 0x0E\n    mov bh, 0x00\n    int 0x10\n    jmp print_string\n.done:\n    ret\n\nloading_msg db 'Loading {os_name}...', 0x0D, 0x0A, 0\n\ntimes 510 - ($ - $$) db 0\ndw 0xAA55\n"""

    def render_kernel_asm(self, os_name):
        return f"""; Generated by OS Maker\n; OS: {os_name}\n\n[BITS 16]\n[ORG 0x1000]\n\nstart:\n    mov ax, 0xB800\n    mov es, ax\n    xor di, di\n    mov si, welcome_msg\n\n.loop:\n    lodsb\n    or al, al\n    jz .done\n    mov byte [es:di], al\n    inc di\n    mov byte [es:di], 0x07\n    inc di\n    jmp .loop\n\n.done:\n    cli\n    hlt\n    jmp $\n\nwelcome_msg db 'Welcome to {os_name}', 0\n"""

    def render_desktop_preview(self, os_name, author):
        return f'''import tkinter as tk\n\n\nclass Windows7Preview:\n    def __init__(self, title: str, author: str):\n        self.root = tk.Tk()\n        self.root.title(f"{{title}} Desktop")\n        self.root.geometry("1280x720")\n        self.root.minsize(900, 600)\n        self.root.configure(bg="#4f8edc")\n\n        self.desktop = tk.Canvas(self.root, bg="#4f8edc", highlightthickness=0)\n        self.desktop.pack(fill="both", expand=True)\n\n        self.wallpaper = tk.Label(\n            self.desktop,\n            text="",\n            bg="#4f8edc",\n            font=("Segoe UI", 12),\n            fg="white",\n        )\n        self.wallpaper.place(x=0, y=0, relwidth=1, relheight=1)\n\n        self.taskbar = tk.Frame(self.root, bg="#d9d9d9", height=44)\n        self.taskbar.pack(fill="x", side="bottom")\n\n        self.start_button = tk.Button(\n            self.taskbar,\n            text="Start",\n            width=10,\n            height=1,\n            bg="#2f9d4a",\n            fg="white",\n            font=("Segoe UI", 10, "bold"),\n            relief="flat",\n        )\n        self.start_button.pack(side="left", padx=(8, 10), pady=6)\n\n        icon_frame = tk.Frame(self.desktop, bg="#4f8edc")\n        icon_frame.place(x=18, y=20)\n\n        desktop_items = [\n            ("Computer", 0),\n            ("Documents", 1),\n            ("Pictures", 2),\n            ("Network", 3),\n        ]\n\n        for label, index in desktop_items:\n            tile = tk.Label(\n                icon_frame,\n                text=label,\n                fg="white",\n                bg="#4f8edc",\n                font=("Segoe UI", 10),\n                compound="top",\n                pady=8,\n            )\n            tile.grid(row=index, column=0, padx=8, pady=8)\n\n        self.title_label = tk.Label(\n            self.desktop,\n            text=f"{{title}}\\nby {{author}}",\n            fg="white",\n            bg="#4f8edc",\n            font=("Segoe UI", 20, "bold"),\n            justify="left",\n        )\n        self.title_label.place(x=600, y=140)\n\n        self.clock = tk.Label(\n            self.taskbar,\n            text="12:00 PM",\n            bg="#d9d9d9",\n            fg="#1b1b1b",\n            font=("Segoe UI", 10, "bold"),\n        )\n        self.clock.pack(side="right", padx=14)\n\n    def run(self):\n        self.root.mainloop()\n\n\nif __name__ == "__main__":\n    Windows7Preview("{os_name}", "{author}").run()\n'''

    def render_makefile(self):
        return """NASM = nasm\nBIN = boot.bin\nKERNEL = kernel.bin\n\nall: $(BIN) $(KERNEL)\n\n$(BIN): boot.asm\n\t$(NASM) -f bin -o $(BIN) boot.asm\n\n$(KERNEL): kernel.asm\n\t$(NASM) -f bin -o $(KERNEL) kernel.asm\n\nclean:\n\trm -f $(BIN) $(KERNEL)\n"""

    def render_qemu_script(self):
        return """#!/usr/bin/env bash\nqemu-system-i386 -drive file=boot.bin,format=raw,if=floppy\n"""

    def render_readme(self, os_name, author):
        return f"""# {os_name}\n\nGenerated by {author} using the OS Maker tool.\n\nThis project is a minimal x86 assembly starter and a Windows 7-inspired desktop mockup.\n\n## Build\n\n```bash\nnasm -f bin -o boot.bin boot.asm\n# Optional: kernel build\nnasm -f bin -o kernel.bin kernel.asm\n```\n\n## Run\n\n```bash\nqemu-system-i386 -drive file=boot.bin,format=raw,if=floppy\n```\n\n## Notes\n\nThis is an educational OS starter, not a full replacement for Windows.\n"""

    def generate_project(self):
        os_name = self.name_var.get().strip() or "MyWin7OS"
        author = self.author_var.get().strip() or "Your Name"

        safe_name = "".join(ch if ch.isalnum() or ch in ("-", "_") else "_" for ch in os_name).strip("_") or "MyWin7OS"
        project_dir = os.path.join(os.getcwd(), "generated", safe_name.lower())

        try:
            os.makedirs(project_dir, exist_ok=True)
        except OSError as exc:
            messagebox.showerror("Generation failed", f"Unable to create output directory: {exc}")
            return

        files = {
            "boot.asm": self.render_boot_asm(os_name),
            "kernel.asm": self.render_kernel_asm(os_name),
            "desktop.py": self.render_desktop_preview(os_name, author),
            "Makefile": self.render_makefile(),
            "run_qemu.sh": self.render_qemu_script(),
            "README.md": self.render_readme(os_name, author),
        }

        for file_name, content in files.items():
            path = os.path.join(project_dir, file_name)
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(content)

        try:
            os.chmod(os.path.join(project_dir, "run_qemu.sh"), 0o755)
        except OSError:
            pass

        self.log(f"Created project folder: {project_dir}")
        for file_name in files:
            self.log(f"  - {file_name}")

        if shutil.which("nasm"):
            build_target = os.path.join(project_dir, "boot.bin")
            try:
                result = subprocess.run(["nasm", "-f", "bin", "-o", build_target, os.path.join(project_dir, "boot.asm")], capture_output=True, text=True)
                if result.returncode == 0:
                    self.log("Build succeeded: boot.bin created.")
                else:
                    self.log("Build warning: NASM assembled the source but produced a non-zero exit code.")
                    self.log(result.stderr.strip() or result.stdout.strip())
            except Exception as exc:  # pragma: no cover - environment dependent
                self.log(f"Build warning: {exc}")
        else:
            self.log("NASM not found. Install nasm to compile the bootloader automatically.")

        messagebox.showinfo("Project generated", f"Your OS project was created in:\n{project_dir}")


def main():
    app = OSMakerApp()
    app.mainloop()


if __name__ == "__main__":
    main()
